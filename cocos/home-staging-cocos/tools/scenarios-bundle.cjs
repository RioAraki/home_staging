// cocos/home-staging-cocos/tools/scenarios-bundle.cjs
// Bundle the per-level sources md/scenarios/<id>.json (ordered by _index.json)
// back into md/maps_data.yaml — the artifact both consumers read
// (cocos yaml2json.cjs, app/ `import @data/maps_data.yaml`).
const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');

const ROOT = path.resolve(__dirname, '..', '..', '..'); // home_staging/
const DIR = path.join(ROOT, 'md', 'scenarios');
const OUT = path.join(ROOT, 'md', 'maps_data.yaml');

const index = JSON.parse(fs.readFileSync(path.join(DIR, '_index.json'), 'utf-8'));
// Any *.json on disk not listed in _index.json is appended (alpha) so new
// editor-created scenarios are never silently dropped.
const onDisk = fs.readdirSync(DIR)
  .filter((f) => f.endsWith('.json') && f !== '_index.json')
  .map((f) => f.slice(0, -5));
const ordered = [...index];
for (const id of onDisk.sort()) if (!ordered.includes(id)) ordered.push(id);

const scenarios = ordered.map((id) => {
  const p = path.join(DIR, `${id}.json`);
  if (!fs.existsSync(p)) throw new Error(`indexed scenario missing file: ${id}.json`);
  return JSON.parse(fs.readFileSync(p, 'utf-8'));
});

const header = '# AUTO-GENERATED by tools/scenarios-bundle.cjs from md/scenarios/*.json — do not edit by hand.\n';
const body = yaml.dump({ scenarios }, { lineWidth: -1, noRefs: true });
fs.writeFileSync(OUT, header + body, 'utf-8');
console.log(`bundled ${scenarios.length} scenarios -> ${OUT}`);
